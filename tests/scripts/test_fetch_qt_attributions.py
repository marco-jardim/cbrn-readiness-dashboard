def _item(script: ModuleType, **changes: object) -> Any:
    values: dict[str, object] = {
        "repo": "qtbase",
        "json_path": "src/3rdparty/zlib/qt_attribution.json",
        "id": "zlib",
        "name": "zlib",
        "version": "1.3.1",
        "qt_module": "qtcore",
        "qt_usage": "Used in Qt Core.",
        "paths": ("src/3rdparty/zlib",),
        "license": "zlib License",
        "license_id": "Zlib",
        "license_files": ("src/3rdparty/zlib/LICENSE",),
        "copyright": ("Copyright (C) Jean-loup Gailly and Mark Adler",),
        "copyright_file": None,
    }
    values.update(changes)
    return script.Attribution(**values)


def test_a_section_states_the_component_and_the_full_licence_text(script: ModuleType) -> None:
    item = _item(script)
    block = script.LicenceBlock("src/3rdparty/zlib/LICENSE", "The zlib licence text.\nLine two.")
    text = script.render_section(7, item, [block])
    assert "[7] zlib\n" in text
    assert "Version: 1.3.1\n" in text
    assert "Qt repository and path: qtbase/src/3rdparty/zlib\n" in text
    assert "License: zlib License\n" in text
    assert "License id: Zlib\n" in text
    assert "Copyright:\n  Copyright (C) Jean-loup Gailly and Mark Adler\n" in text
    heading = "Licence text (qtbase/src/3rdparty/zlib/LICENSE):"
    assert f"{heading}\n\nThe zlib licence text.\nLine two." in text
    assert text.endswith("\n")


def test_a_section_refers_to_an_identical_text_printed_earlier(script: ModuleType) -> None:
    item = _item(script)
    block = script.LicenceBlock("src/3rdparty/zlib/LICENSE", "text", same_as=3)
    text = script.render_section(9, item, [block])
    assert "identical to the text printed in section [3]" in text
    assert "\ntext" not in text


