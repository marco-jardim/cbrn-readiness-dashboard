def test_parse_errors_are_reported_with_the_file(script: ModuleType) -> None:
    with pytest.raises(script.ParseError, match=r"qtbase/a/qt_attribution\.json"):
        script.parse_attribution("qtbase", "a/qt_attribution.json", "{broken")
    with pytest.raises(script.ParseError, match="not a JSON object"):
        script.parse_attribution("qtbase", "a/qt_attribution.json", json.dumps(["text"]))
