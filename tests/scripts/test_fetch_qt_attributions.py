def test_the_vendored_notices_exist_and_state_the_installed_qt_version(script: ModuleType) -> None:
    """A PySide6 upgrade fails here until the notices are fetched again."""
    from PySide6 import QtCore

    path = VENDORED / script.NOTICES_NAME
    assert path.is_file(), (
        f"{path} is missing: run 'uv run python scripts/fetch_qt_attributions.py' "
        "(needs network access) and commit the result"
    )
    text = path.read_text(encoding="utf-8")
    assert text.startswith("Qt third-party notices\n")
    assert script.notices_qt_version(text) == QtCore.qVersion()
    assert f"Source tag: v{QtCore.qVersion()}\n" in text
    assert "\r" not in text


def test_the_vendored_manifest_matches_the_notices(script: ModuleType) -> None:
    from PySide6 import QtCore

    path = VENDORED / script.MANIFEST_NAME
    assert path.is_file(), f"{path} is missing: run scripts/fetch_qt_attributions.py"
    manifest = json.loads(path.read_text(encoding="utf-8"))
    assert manifest["qt_version"] == QtCore.qVersion()
    assert manifest["repositories"] == list(script.QT_REPOS)
    assert manifest["files"]
    for entry in manifest["files"]:
        assert entry["url"].startswith("https://")
        assert len(entry["sha256"]) == 64
    fetched = {entry["url"] for entry in manifest["files"]}
    for repo in script.QT_REPOS:
        assert script.tree_url(repo, f"v{QtCore.qVersion()}") in fetched


def test_the_vendored_notices_cover_every_repository(script: ModuleType) -> None:
    text = (VENDORED / script.NOTICES_NAME).read_text(encoding="utf-8")
    assert "Components: " in text
    assert "Qt source repositories: " + ", ".join(script.QT_REPOS) in text
    assert "qtbase: " in text  # at least one qtbase component in the contents list
