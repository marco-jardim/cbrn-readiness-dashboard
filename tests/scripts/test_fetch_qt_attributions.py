def test_a_failing_fetch_stops_the_run(script: ModuleType) -> None:
    def get(url: str) -> bytes:
        raise script.FetchError(f"HTTP 404 (Not Found) for {url}")

    with pytest.raises(script.FetchError, match="HTTP 404"):
        script.build("6.12.0", get, repos=("qtbase",))


def test_main_reports_an_error_without_a_traceback(
    script: ModuleType,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    def failing(url: str, *, timeout: float = 0.0) -> bytes:
        raise script.FetchError(f"HTTP 403 (Forbidden) for {url}")

    monkeypatch.setattr(script, "http_get", failing)
    assert script.main(["--qt-version", "6.12.0", "--out", str(tmp_path / "out")]) == 1
    assert "error: HTTP 403" in capsys.readouterr().err
    assert not (tmp_path / "out" / script.NOTICES_NAME).exists()


