def test_notices_are_sorted_by_repository_then_name_and_every_component_has_its_text(
    script: ModuleType,
) -> None:
    items = [
        _item(script, repo="qtsvg", name="Zeta", license_files=("L",), json_path="z/q.json"),
        _item(script, repo="qtbase", name="beta", license_files=("L",), json_path="b/q.json"),
        _item(script, repo="qtbase", name="Alpha", license_files=("M",), json_path="a/q.json"),
    ]
    files = {
        ("qtsvg", "L"): "Licence L\r\n",
        ("qtbase", "L"): "Licence L",
        ("qtbase", "M"): "Licence M",
    }
    text = script.render_notices("6.12.0", items, files)
    assert text.startswith("Qt third-party notices\n")
    assert script.notices_qt_version(text) == "6.12.0"
    assert "Source tag: v6.12.0\n" in text
    assert "Components: 3\n" in text
    assert text.index("[1] Alpha\n") < text.index("[2] beta\n") < text.index("[3] Zeta\n")
    assert "[1] qtbase: Alpha 1.3.1" in text  # contents list
    # The first copy of "Licence L" is printed in full (section 2); section 3 refers to it.
    assert text.count("Licence L") == 1
    assert "Licence M" in text
    assert "identical to the text printed in section [2]" in text
    assert "\r" not in text


