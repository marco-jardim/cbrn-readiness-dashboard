def test_an_object_with_one_licence_file_and_a_copyright_string(script: ModuleType) -> None:
    items = script.parse_attribution("qtbase", "src/3rdparty/qt_attribution.json", OBJECT_JSON)
    assert len(items) == 1
    item = items[0]
    assert item.repo == "qtbase"
    assert item.json_path == "src/3rdparty/qt_attribution.json"
    assert item.name == "FreeType"
    assert item.version == "2.13.2"
    assert item.qt_module == "qtgui"
    assert item.qt_usage == "Used in the xcb and Windows plugins."
    assert item.paths == ("src/3rdparty/freetype",)
    assert item.license == "FreeType License"
    assert item.license_id == "FTL"
    assert item.license_files == ("src/3rdparty/freetype/docs/FTL.TXT",)
    assert item.copyright == ("Copyright 1996-2002 by David Turner",)
    assert item.copyright_file is None


def test_a_list_with_licence_files_and_copyright_lists(script: ModuleType) -> None:
    first, second = script.parse_attribution("qtsvg", "src/x/qt_attribution.json", LIST_JSON)
    assert first.name == "Alpha"
    assert first.paths == ("src/x",)
    assert first.license_files == ("src/x/LICENSE.a", "src/LICENSE.shared")
    assert first.copyright == ("Copyright (C) A", "Copyright (C) B\nCopyright (C) C")
    assert first.copyright_file == "src/x/COPYRIGHT"
    assert second.name == "Beta"
    assert second.version == ""
    assert second.paths == ("src/x",)  # no Path: the folder of the JSON file
    assert second.license_files == ("src/x/LICENSE.b", "src/x/LICENSE.b2")  # merged, no repeat
    assert second.copyright == ()


