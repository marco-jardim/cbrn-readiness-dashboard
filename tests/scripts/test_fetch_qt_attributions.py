def test_parse_tree_keeps_blobs_and_rejects_a_truncated_listing(script: ModuleType) -> None:
    listing = {
        "tree": [
            {"path": "src", "type": "tree"},
            {"path": "src/qt_attribution.json", "type": "blob"},
            {"path": "LICENSE", "type": "blob"},
        ],
        "truncated": False,
    }
    assert script.parse_tree(json.dumps(listing)) == ["src/qt_attribution.json", "LICENSE"]
    listing["truncated"] = True
    with pytest.raises(script.ParseError, match="truncated"):
        script.parse_tree(json.dumps(listing))
    with pytest.raises(script.ParseError):
        script.parse_tree("not json")
    with pytest.raises(script.ParseError):
        script.parse_tree(json.dumps({"message": "Not Found"}))


def test_urls_use_the_version_tag(script: ModuleType) -> None:
    assert script.tag_for("6.12.0") == "v6.12.0"
    assert script.tree_url("qtbase", "v6.12.0") == (
        "https://api.github.com/repos/qt/qtbase/git/trees/v6.12.0?recursive=1"
    )
    assert script.raw_url("qtsvg", "v6.12.0", "src/a b/LICENSE") == (
        "https://raw.githubusercontent.com/qt/qtsvg/v6.12.0/src/a%20b/LICENSE"
    )
    with pytest.raises(script.AttributionError):
        script.tag_for("6.12")


